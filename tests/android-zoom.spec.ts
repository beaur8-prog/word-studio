import { test, expect } from '@playwright/test';
import path from 'node:path';
import { fixture, assertInputs, zoomScale, pointOnPage, wheel } from './zoom-test-helpers';
for (const tablet of [false, true]) test(`${tablet ? 'tablet' : 'phone'} document reading/editor/fullscreen and HWP views accept trackpad and Ctrl-wheel`, async ({ page }) => {
  test.setTimeout(90000);
  if (tablet) await page.setViewportSize({ width: 1280, height: 1000 });
  await page.goto('/'); await page.locator('input[type=file]').first().setInputFiles({ name: 'zoom.docx', mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', buffer: await fixture() });
  const reader = page.locator('.android-paper-viewport'); await expect(reader).toBeVisible();
  if (await page.getByRole('button', { name: '알림 닫기', exact: true }).count()) await page.getByRole('button', { name: '알림 닫기', exact: true }).click();
  const paper = page.locator('[data-android-page="3"] .print-page');
  await reader.evaluate(el => { const slot = el.querySelector<HTMLElement>('[data-android-page="3"]')!; el.scrollTop = parseFloat(slot.style.top) + 100; });
  await expect(paper).toBeVisible(); const before = await pointOnPage(reader, paper), base = await zoomScale(reader);
  await wheel(page, reader); await expect.poll(() => zoomScale(reader)).toBeGreaterThan(base * 1.1);
  const after = await pointOnPage(reader, paper); expect(Math.abs(after.x - before.x) * await zoomScale(reader)).toBeLessThan(2); expect(Math.abs(after.y - before.y) * await zoomScale(reader)).toBeLessThan(2);
  await assertInputs(page, reader);
  await page.locator('.android-topbar').getByRole('button', { name: '편집 모드', exact: true }).click();
  const editor = tablet ? page.locator('.office-shell .tiptap') : page.getByLabel('Android 문서 편집 영역'); await expect(editor).toHaveAttribute('contenteditable', 'true');
  const text = await editor.textContent();
  await assertInputs(page, page.locator(tablet ? '.office-shell .document-workspace' : '.android-editor-scroll'));
  expect(await editor.textContent()).toBe(text);
  await page.getByRole('button', { name: '전체 화면 뷰어', exact: true }).filter({ visible: true }).click();
  const full = page.locator('.android-presentation-viewport'); await expect(full).toBeVisible();
  await assertInputs(page, full); const scale = await zoomScale(full);
  await page.keyboard.press('ArrowRight'); await expect.poll(() => zoomScale(full)).toBeCloseTo(scale, 5);
  await page.keyboard.press('Escape'); await expect(page.locator('.android-presentation')).toHaveCount(0);
  await page.locator('.android-shell > input[type=file]').setInputFiles(path.resolve('tests/fixtures/hwp/landscape-pagination.hwp'));
  const hwp = page.getByRole('dialog', { name: 'HWP 읽기', exact: true }); await expect(hwp.getByTestId('hwp-page')).toBeVisible();
  await assertInputs(page, hwp.locator('.hwp-viewport'));
  await hwp.getByRole('button', { name: '한글 전체 화면 뷰어', exact: true }).click(); await expect(full).toBeVisible();
  await assertInputs(page, full); await page.keyboard.press('Escape'); await expect(hwp.getByTestId('hwp-page')).toBeVisible();
});
